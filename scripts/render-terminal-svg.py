#!/usr/bin/env python3
"""Render stdin text as a deterministic SVG "terminal window".

SVG instead of a PNG screenshot: this renders a terminal-window look from
plain text (title-bar dots, monospace body, one ``<text>`` element per
input line) so the image is reproducible from the repository on every run
and needs no binary asset. It is stdlib-only — no Pillow, no cairosvg — so
it has no extra dependency to install.

To regenerate ``docs/img/check.svg`` from the real CLI output, run this
exact command (the comment text is also what lands at the top of the
generated file, so the two must always be regenerated together):

    cargo arch-lint check examples/sample-project 2>/dev/null | python3 scripts/render-terminal-svg.py --title "cargo arch-lint check examples/sample-project" --regenerate-comment "Generated by scripts/render-terminal-svg.py from: cargo arch-lint check examples/sample-project (2>/dev/null, text format)" > docs/img/check.svg

The real `arch-lint check` output carries no ANSI escape codes when stdout
is not a TTY (verified against the actual binary output), so this script
does not parse ANSI SGR sequences. Instead it looks at the first word after
a line's leading whitespace and colours the line if that word is "error:"
or "warning:" (so a help line like "= help: ... .ok_or(Error)?" is not
miscoloured just because the word "Error" appears in it); everything else
is rendered in the default foreground colour. Empty input produces an
empty window (title bar, no body text) and the script still exits 0.
"""

from __future__ import annotations

import argparse
import sys

FONT_SIZE = 14
LINE_HEIGHT = int(FONT_SIZE * 1.5)
CHAR_WIDTH = FONT_SIZE * 0.6  # monospace approximation, no font metrics needed
PAD_X = 16
TITLE_BAR_HEIGHT = 32
PAD_TOP = 12
PAD_BOTTOM = 16
MIN_WIDTH = 360

BG_DARK = "#1e1e2e"
TITLE_BAR = "#2a2a3c"
FG_DEFAULT = "#d4d4d4"
FG_ERROR = "#f38ba8"
FG_WARNING = "#f9e2af"
FG_MUTED = "#6c7086"
DOT_RED = "#ff5f56"
DOT_YELLOW = "#ffbd2e"
DOT_GREEN = "#27c93f"


def escape_xml(text: str) -> str:
    return (
        text.replace("&", "&amp;")
        .replace("<", "&lt;")
        .replace(">", "&gt;")
        .replace('"', "&quot;")
    )


def line_color(line: str) -> str:
    """Pick a foreground colour for one line.

    Only the first whitespace-delimited token after the line's leading
    indentation is checked, against the literal "error:" / "warning:" that
    `arch-lint check`'s text format prints (e.g. "  error: .unwrap() is
    forbidden ..."). A substring match would also light up a line like
    "= help: ... .ok_or(Error)?" just because the word "Error" appears
    inside it, which is the bug this first-token rule avoids.
    """
    stripped = line.strip()
    first_token = stripped.split(maxsplit=1)[0].lower() if stripped else ""
    if first_token == "error:":
        return FG_ERROR
    if first_token == "warning:":
        return FG_WARNING
    if stripped.startswith("="):
        return FG_MUTED
    return FG_DEFAULT


def render_svg(lines: list[str], title: str, regenerate_comment: str) -> str:
    longest = max((len(line) for line in lines), default=0)
    width = max(MIN_WIDTH, int(longest * CHAR_WIDTH) + PAD_X * 2)
    body_height = len(lines) * LINE_HEIGHT
    height = TITLE_BAR_HEIGHT + PAD_TOP + body_height + PAD_BOTTOM

    parts: list[str] = []
    if regenerate_comment:
        safe_comment = regenerate_comment.replace("--", "- -")
        parts.append(f"<!-- {safe_comment} -->")
    parts.append(
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" '
        f'height="{height}" viewBox="0 0 {width} {height}" '
        f'font-family="Menlo, Consolas, \'DejaVu Sans Mono\', monospace" '
        f'role="img" aria-label="{escape_xml(title)}">'
    )
    parts.append(f'<rect width="{width}" height="{height}" fill="{BG_DARK}" rx="8"/>')
    parts.append(
        f'<rect width="{width}" height="{TITLE_BAR_HEIGHT}" fill="{TITLE_BAR}" rx="8"/>'
    )
    parts.append(
        f'<rect y="{TITLE_BAR_HEIGHT - 8}" width="{width}" height="8" fill="{TITLE_BAR}"/>'
    )
    # Title-bar traffic-light dots.
    dot_y = TITLE_BAR_HEIGHT // 2
    for index, color in enumerate((DOT_RED, DOT_YELLOW, DOT_GREEN)):
        dot_x = 16 + index * 18
        parts.append(f'<circle cx="{dot_x}" cy="{dot_y}" r="6" fill="{color}"/>')
    if title:
        parts.append(
            f'<text x="{width // 2}" y="{dot_y + 4}" text-anchor="middle" '
            f'font-size="12" fill="{FG_MUTED}">{escape_xml(title)}</text>'
        )

    text_x = PAD_X
    first_baseline = TITLE_BAR_HEIGHT + PAD_TOP + FONT_SIZE
    for row, line in enumerate(lines):
        y = first_baseline + row * LINE_HEIGHT
        color = line_color(line)
        parts.append(
            f'<text x="{text_x}" y="{y}" font-size="{FONT_SIZE}" '
            f'fill="{color}" xml:space="preserve">{escape_xml(line)}</text>'
        )

    parts.append("</svg>")
    return "\n".join(parts)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--title",
        default="",
        help="optional title-bar label (e.g. the command that produced stdin)",
    )
    parser.add_argument(
        "--regenerate-comment",
        default="",
        help=(
            "exact command to regenerate this SVG, recorded verbatim as an "
            "XML comment at the top of the output"
        ),
    )
    args = parser.parse_args()

    raw = sys.stdin.read()
    lines = raw.splitlines() if raw else []

    svg = render_svg(lines, args.title, args.regenerate_comment)
    sys.stdout.write(svg)
    sys.stdout.write("\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
