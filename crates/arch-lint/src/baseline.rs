//! Baseline: freeze today's violations so arch-lint can be turned on in CI
//! before a codebase is clean.
//!
//! A [`Baseline`] is a TOML file the user commits. It identifies a violation
//! by `(code, file, message)` plus a per-file count — exactly `PHPStan`'s
//! scheme, and deliberately **not** `(code, file, line)`: a line number
//! invalidates the entry on the next unrelated edit above it, which is why
//! every mature baseline tool in the genre (`PHPStan`, detekt's
//! `RuleID:FileName:Signature`, dependency-cruiser) keys on something other
//! than position. `file` is the root-relative path exactly as it appears in
//! [`Violation::location`]'s `file`; `message` is [`Violation::message`]
//! verbatim. This is computed centrally by [`fingerprint`] rather than by
//! each rule — [`Violation`] has no `fingerprint` field, so adding one would
//! have broken every existing `Violation::new(...)` struct literal across the
//! rule crates — and the same function backs the SARIF `partialFingerprints`
//! planned for issue #11.
//!
//! An entry survives an edit as long as the edit does not change the message
//! or move the violation to a different file — true of every rule whose
//! message names an item, a path or a scope edge rather than a measurement:
//! built-in rule messages are otherwise constant per pattern; `ALD003` and
//! `ALD004` name the denied scope edge *and* the specific `use` path or
//! inline reference (e.g. `"...: ...::db::connect (scope domain →
//! scope infra)"`, quoting omitted here only to keep this one clause
//! readable); `ALD010` and `ALD011` name the scope edge only (`"domain →
//! infra"`). None of these change on an edit that does not touch the
//! reference or the scopes involved.
//!
//! **`AL004` (`handler-complexity`) used to be the exception**: its message
//! embedded the measured size (`"Match expression has 12 arms (max: 5)"`),
//! so adding or removing an arm, line or variant in an already-baselined
//! handler changed the fingerprint — the old entry went stale and the
//! violation was reported as new, even though nothing about the handler's
//! *shape* changed. The measurement now lives in the violation's
//! [`Suggestion`](arch_lint_core::Suggestion) instead (e.g. `"61 lines,
//! limit 50 — ..."`), and the message names only the item (e.g. ``Handler
//! `handle` exceeds the line limit``); `AL004` is no longer an exception —
//! every built-in rule's fingerprint is now stable across an edit that only
//! changes a measured count. `fingerprint` does not normalize digits to
//! paper over a rule that still put one in `message`; this baseline module
//! stays a straightforward reflection of whatever the rule chose to put
//! there.
//!
//! **`ALD009` (`acyclic`)** reports one violation per cycle, attributed to
//! the *first* edge's call site in cycle-path order (not every edge — the
//! other edges are [`Violation::labels`], which this scheme does not key
//! on). The cycle's full scope list is named in the message, but `file` is
//! whichever file that first edge happens to live in; a new reference that
//! changes which edge is first (e.g. one added in a scope earlier in the
//! cycle) moves the entry to a different `file` — the old one goes stale,
//! a new one appears — even when the cycle itself is unchanged.
//!
//! **Severity is not part of the key.** A baselined warning stays
//! suppressed if a later `[rules.<name>] severity = "error"` override (or
//! the reverse) changes its severity — `(code, file, message)` does not
//! include it, by design: a baseline is about which violations are known,
//! not how loudly they are reported.
//!
//! ```no_run
//! use arch_lint::baseline::Baseline;
//! use arch_lint::Session;
//!
//! # fn main() -> Result<(), Box<dyn std::error::Error>> {
//! // First run: record today's violations.
//! let result = Session::discover(".")?.run()?;
//! Baseline::from_result(&result).save("arch-lint.baseline.toml")?;
//!
//! // Later runs: only new violations are reported.
//! let baseline = Baseline::load("arch-lint.baseline.toml")?;
//! let applied = Session::discover(".")?.with_baseline(baseline).run_with_baseline()?;
//! eprintln!("baseline: {} suppressed, {} stale", applied.suppressed, applied.stale.len());
//! # Ok(())
//! # }
//! ```

use arch_lint_core::{LintResult, Violation};
use serde::{Deserialize, Serialize};
use std::collections::HashMap;
use std::path::{Path, PathBuf};

/// Comment written atop every baseline file written by [`Baseline::save`].
const BASELINE_HEADER: &str = "\
# Generated by `arch-lint check --update-baseline`. Entries are matched by
# code, file and message, with a per-file count; line numbers are not stored.
";

/// Computes the identity key of a violation for baseline purposes:
/// `code`, [`Violation::location`]'s `file`, and [`Violation::message`]
/// verbatim, joined with `|` into one readable display string — not a hash
/// — so it can be inspected on sight and reused as-is for SARIF
/// `partialFingerprints` (issue #11).
///
/// This string is for display only; [`Baseline::from_result`] and [`apply`]
/// match on the `(code, file, message)` key tuple itself, not on this
/// joined text, so a `|` occurring inside a message does not create a false
/// collision or split a match.
///
/// Deliberately excludes the line and column: see the [module docs](self)
/// for why.
#[must_use]
pub fn fingerprint(v: &Violation) -> String {
    format!("{}|{}|{}", v.code, v.location.file.display(), v.message)
}

/// The `(code, file, message)` triple [`fingerprint`] is built from, used as
/// the matching key for both [`Baseline::from_result`] and [`apply`].
type Key = (String, PathBuf, String);

fn key_of(v: &Violation) -> Key {
    (v.code.clone(), v.location.file.clone(), v.message.clone())
}

/// One recorded violation identity: how many times `(code, file, message)`
/// was observed when the baseline was written.
///
/// Line numbers are deliberately not stored — see the [module docs](self).
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
#[non_exhaustive]
pub struct Entry {
    /// Rule code (e.g. `"AL001"`).
    pub code: String,
    /// Root-relative file path, exactly as in `Violation.location.file`.
    pub file: PathBuf,
    /// The violation message, verbatim.
    pub message: String,
    /// How many times this `(code, file, message)` was observed.
    pub count: usize,
}

/// TOML document shape: `[[entry]]` repeated.
///
/// `deny_unknown_fields` on both this and [`Entry`] is deliberate: without
/// it, a typo like `[[entries]]` (plural) or `cde = "AL001"` silently
/// parses as zero entries or a dropped field instead of failing — a user
/// who hand-edits the file would otherwise get a baseline that quietly
/// stops matching anything.
#[derive(Debug, Default, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
struct Document {
    #[serde(default)]
    entry: Vec<Entry>,
}

/// A loaded or freshly computed set of known violations.
///
/// Build one with [`Baseline::from_result`] (from a fresh analysis) or
/// [`Baseline::load`] (from a committed file), apply it with [`apply`] (or
/// [`crate::Session::run_with_baseline`]), and persist it with
/// [`Baseline::save`].
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Baseline {
    entries: Vec<Entry>,
}

impl Baseline {
    /// Builds a baseline from every violation in `result`, regardless of
    /// severity — the baseline authoring step (`--update-baseline`) always
    /// runs the full analysis, so a violation that is a warning today and
    /// becomes an error tomorrow does not slip through unbaselined.
    ///
    /// Entries are sorted by `(file, code, message)`, so the written file is
    /// deterministic and diffs cleanly across runs.
    #[must_use]
    pub fn from_result(result: &LintResult) -> Self {
        let mut counts: HashMap<Key, usize> = HashMap::new();
        for v in &result.violations {
            *counts.entry(key_of(v)).or_insert(0) += 1;
        }
        Self {
            entries: sorted_entries(counts),
        }
    }

    /// Loads a baseline from a TOML file.
    ///
    /// # Errors
    ///
    /// Returns [`BaselineError::Io`] if `path` cannot be read, and
    /// [`BaselineError::Parse`] if it is not a valid baseline document.
    pub fn load(path: impl AsRef<Path>) -> Result<Self, BaselineError> {
        let path = path.as_ref();
        let content = std::fs::read_to_string(path).map_err(|source| BaselineError::Io {
            path: path.to_path_buf(),
            source,
        })?;
        let doc: Document = toml::from_str(&content).map_err(|source| BaselineError::Parse {
            path: path.to_path_buf(),
            source,
        })?;

        // Entries may not be sorted on disk (hand-edited file); re-sort, and
        // fold duplicate (code, file, message) rows together defensively,
        // the same way `apply` would treat them.
        let mut counts: HashMap<Key, usize> = HashMap::new();
        for entry in doc.entry {
            *counts
                .entry((entry.code, entry.file, entry.message))
                .or_insert(0) += entry.count;
        }
        Ok(Self {
            entries: sorted_entries(counts),
        })
    }

    /// Writes this baseline to a TOML file, with the standard header comment.
    ///
    /// # Errors
    ///
    /// Returns [`BaselineError::Serialize`] if the entries cannot be
    /// serialized (this should not happen for well-formed entries), and
    /// [`BaselineError::Io`] if `path` cannot be written.
    pub fn save(&self, path: impl AsRef<Path>) -> Result<(), BaselineError> {
        let path = path.as_ref();
        let doc = Document {
            entry: self.entries.clone(),
        };
        let body = toml::to_string_pretty(&doc).map_err(BaselineError::Serialize)?;
        let content = format!("{BASELINE_HEADER}{body}");
        std::fs::write(path, content).map_err(|source| BaselineError::Io {
            path: path.to_path_buf(),
            source,
        })
    }

    /// Returns `true` if this baseline has no entries.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// The baseline's entries, sorted by `(file, code, message)`.
    #[must_use]
    pub fn entries(&self) -> &[Entry] {
        &self.entries
    }
}

fn sorted_entries(counts: HashMap<Key, usize>) -> Vec<Entry> {
    let mut entries: Vec<Entry> = counts
        .into_iter()
        .map(|((code, file, message), count)| Entry {
            code,
            file,
            message,
            count,
        })
        .collect();
    entries.sort_by(|a, b| (&a.file, &a.code, &a.message).cmp(&(&b.file, &b.code, &b.message)));
    entries
}

/// Everything that can go wrong loading or saving a [`Baseline`].
#[derive(Debug, thiserror::Error)]
pub enum BaselineError {
    /// The baseline file could not be read or written.
    #[error("Failed to access baseline file {path}")]
    Io {
        /// Path that could not be accessed.
        path: PathBuf,
        /// Underlying IO error.
        #[source]
        source: std::io::Error,
    },

    /// The baseline file is not valid baseline TOML.
    #[error("Failed to parse baseline file {path}")]
    Parse {
        /// Path the content came from.
        path: PathBuf,
        /// Underlying parse error.
        #[source]
        source: toml::de::Error,
    },

    /// The baseline's entries could not be serialized.
    #[error("Failed to serialize baseline")]
    Serialize(#[source] toml::ser::Error),
}

/// The result of matching a [`LintResult`] against a [`Baseline`].
#[non_exhaustive]
#[derive(Debug)]
pub struct Applied {
    /// Only the violations [`apply`] could not match against the baseline —
    /// the ones a CI gate should fail on. `files_checked` is preserved from
    /// the input [`LintResult`].
    pub result: LintResult,
    /// How many violations were matched against the baseline and removed
    /// from `result`.
    pub suppressed: usize,
    /// Baseline entries whose recorded count exceeds what was observed in
    /// this run — i.e. violations that no longer exist. `count` on each is
    /// the unmatched remainder, not the original count. Empty when nothing
    /// in the baseline went stale.
    pub stale: Vec<Entry>,
}

/// Matches every violation in `result` against `baseline`.
///
/// For each violation, one count is consumed from the baseline entry sharing
/// its [`fingerprint`] (`code`, `file`, `message`) if any remain; otherwise
/// the violation is kept as new. Baseline entries with counts left over after
/// every violation has been matched are reported as `stale` — violations
/// that were recorded but no longer occur.
#[must_use]
pub fn apply(result: LintResult, baseline: &Baseline) -> Applied {
    let mut remaining: HashMap<Key, usize> = HashMap::new();
    for entry in &baseline.entries {
        *remaining
            .entry((
                entry.code.clone(),
                entry.file.clone(),
                entry.message.clone(),
            ))
            .or_insert(0) += entry.count;
    }

    let files_checked = result.files_checked;
    let mut new_violations = Vec::with_capacity(result.violations.len());
    let mut suppressed = 0usize;

    for v in result.violations {
        let key = key_of(&v);
        let consumed = match remaining.get_mut(&key) {
            Some(count) if *count > 0 => {
                *count -= 1;
                true
            }
            _ => false,
        };
        if consumed {
            suppressed += 1;
        } else {
            new_violations.push(v);
        }
    }

    let stale = sorted_entries(
        remaining
            .into_iter()
            .filter(|(_, count)| *count > 0)
            .collect(),
    );

    Applied {
        result: LintResult {
            violations: new_violations,
            files_checked,
        },
        suppressed,
        stale,
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use arch_lint_core::{Location, Severity};
    use tempfile::TempDir;

    fn violation(code: &str, file: &str, message: &str) -> Violation {
        Violation::new(
            code,
            "some-rule",
            Severity::Error,
            Location::new(PathBuf::from(file), 1, 1),
            message,
        )
    }

    fn result_of(violations: Vec<Violation>) -> LintResult {
        LintResult {
            violations,
            files_checked: violations_file_count(),
        }
    }

    // A fixed, unrelated-to-content file count, so tests can assert it is
    // preserved rather than recomputed.
    fn violations_file_count() -> usize {
        7
    }

    // ── fingerprint ──

    #[test]
    fn fingerprint_joins_code_file_message() {
        let v = violation("AL001", "src/lib.rs", ".unwrap() is forbidden");
        assert_eq!(fingerprint(&v), "AL001|src/lib.rs|.unwrap() is forbidden");
    }

    #[test]
    fn fingerprint_ignores_line_and_column() {
        let mut a = violation("AL001", "src/lib.rs", "m");
        let mut b = violation("AL001", "src/lib.rs", "m");
        a.location.line = 10;
        b.location.line = 20;
        assert_eq!(fingerprint(&a), fingerprint(&b));
    }

    #[test]
    fn fingerprint_differs_by_message() {
        let a = violation("AL001", "src/lib.rs", "unwrap");
        let b = violation("AL001", "src/lib.rs", "expect");
        assert_ne!(fingerprint(&a), fingerprint(&b));
    }

    // ── Baseline::from_result / entries ──

    #[test]
    fn from_result_counts_duplicates_per_file() {
        let result = result_of(vec![
            violation("AL001", "src/a.rs", "m"),
            violation("AL001", "src/a.rs", "m"),
            violation("AL001", "src/a.rs", "m"),
        ]);
        let baseline = Baseline::from_result(&result);
        assert_eq!(baseline.entries().len(), 1);
        assert_eq!(baseline.entries()[0].count, 3);
    }

    #[test]
    fn from_result_is_sorted_by_file_then_code_then_message() {
        let result = result_of(vec![
            violation("AL002", "src/b.rs", "m"),
            violation("AL001", "src/a.rs", "z"),
            violation("AL001", "src/a.rs", "a"),
        ]);
        let baseline = Baseline::from_result(&result);
        let keys: Vec<(&str, &str, &str)> = baseline
            .entries()
            .iter()
            .map(|e| {
                (
                    e.file.to_str().unwrap(),
                    e.code.as_str(),
                    e.message.as_str(),
                )
            })
            .collect();
        assert_eq!(
            keys,
            vec![
                ("src/a.rs", "AL001", "a"),
                ("src/a.rs", "AL001", "z"),
                ("src/b.rs", "AL002", "m"),
            ]
        );
    }

    #[test]
    fn from_result_is_empty_for_a_clean_result() {
        let baseline = Baseline::from_result(&LintResult::new());
        assert!(baseline.is_empty());
    }

    // ── apply ──

    #[test]
    fn apply_consumes_counts_and_suppresses() {
        let result = result_of(vec![
            violation("AL001", "src/a.rs", "m"),
            violation("AL001", "src/a.rs", "m"),
        ]);
        let baseline = Baseline::from_result(&result);

        let applied = apply(result, &baseline);
        assert!(applied.result.violations.is_empty());
        assert_eq!(applied.suppressed, 2);
        assert!(applied.stale.is_empty());
        assert_eq!(applied.result.files_checked, violations_file_count());
    }

    #[test]
    fn apply_keeps_extras_beyond_the_baselined_count_as_new() {
        let baselined = result_of(vec![violation("AL001", "src/a.rs", "m")]);
        let baseline = Baseline::from_result(&baselined);

        let now = result_of(vec![
            violation("AL001", "src/a.rs", "m"),
            violation("AL001", "src/a.rs", "m"),
        ]);
        let applied = apply(now, &baseline);
        assert_eq!(applied.suppressed, 1);
        assert_eq!(applied.result.violations.len(), 1);
    }

    #[test]
    fn apply_reports_stale_entries_for_the_unmatched_remainder() {
        let baselined = result_of(vec![
            violation("AL001", "src/a.rs", "m"),
            violation("AL001", "src/a.rs", "m"),
        ]);
        let baseline = Baseline::from_result(&baselined);

        // Only one of the two baselined violations still occurs.
        let now = result_of(vec![violation("AL001", "src/a.rs", "m")]);
        let applied = apply(now, &baseline);
        assert_eq!(applied.suppressed, 1);
        assert_eq!(applied.stale.len(), 1);
        assert_eq!(applied.stale[0].count, 1);
        assert_eq!(applied.stale[0].code, "AL001");
    }

    #[test]
    fn apply_is_line_independent() {
        let mut original = violation("AL001", "src/a.rs", "m");
        original.location.line = 5;
        let baseline = Baseline::from_result(&result_of(vec![original]));

        let mut moved = violation("AL001", "src/a.rs", "m");
        moved.location.line = 25; // 10 blank lines inserted above it
        let applied = apply(result_of(vec![moved]), &baseline);

        assert_eq!(applied.suppressed, 1);
        assert!(applied.result.violations.is_empty());
        assert!(applied.stale.is_empty());
    }

    #[test]
    fn apply_matches_a_graph_rule_violation_by_its_scope_edge_message() {
        // The real message shape `ScopeDepVisitor` builds (see
        // `declarative/rules/scope_dep.rs`): the user's configured message,
        // the specific `use` path, and the scope edge — all stable across
        // an unrelated edit, with no line information.
        let edge_message =
            "Domain must be DB-agnostic.: `crate::infra::db::connect` (scope `domain` \u{2192} scope `infra`)";
        let baseline = Baseline::from_result(&result_of(vec![violation(
            "ALD003",
            "src/domain/service.rs",
            edge_message,
        )]));

        let mut shifted = violation("ALD003", "src/domain/service.rs", edge_message);
        shifted.location.line = 99;
        let applied = apply(result_of(vec![shifted]), &baseline);
        assert_eq!(applied.suppressed, 1);
        assert!(applied.result.violations.is_empty());

        // A different edge (different path, different target scope) in the
        // same file is a different fingerprint, not covered by the entry
        // above.
        let other_edge = violation(
            "ALD003",
            "src/domain/service.rs",
            "Domain must be DB-agnostic.: `crate::web::handler::respond` (scope `domain` \u{2192} scope `web`)",
        );
        let applied = apply(result_of(vec![other_edge]), &baseline);
        assert_eq!(applied.suppressed, 0);
        assert_eq!(applied.result.violations.len(), 1);
    }

    // ── load / save round-trip ──

    #[test]
    fn save_then_load_round_trips() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("b.toml");

        let result = result_of(vec![
            violation("AL001", "src/a.rs", "m"),
            violation("AL002", "src/b.rs", "n"),
            violation("AL002", "src/b.rs", "n"),
        ]);
        let baseline = Baseline::from_result(&result);
        baseline.save(&path).expect("save");

        let loaded = Baseline::load(&path).expect("load");
        assert_eq!(loaded, baseline);
    }

    #[test]
    fn save_writes_the_header_comment() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("b.toml");
        Baseline::from_result(&result_of(vec![violation("AL001", "src/a.rs", "m")]))
            .save(&path)
            .expect("save");

        let content = std::fs::read_to_string(&path).unwrap();
        assert!(content.starts_with("# Generated by `arch-lint check --update-baseline`"));
        assert!(content.contains("[[entry]]"));
        assert!(content.contains("code = \"AL001\""));
    }

    #[test]
    fn save_omits_line_numbers() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("b.toml");
        let mut v = violation("AL001", "src/a.rs", "m");
        v.location.line = 123;
        Baseline::from_result(&result_of(vec![v]))
            .save(&path)
            .expect("save");

        let content = std::fs::read_to_string(&path).unwrap();
        assert!(!content.contains("123"), "{content}");
        assert!(!content.contains("line ="), "{content}");
    }

    #[test]
    fn load_missing_file_is_an_io_error() {
        let err = Baseline::load("/nonexistent/arch-lint.baseline.toml").unwrap_err();
        assert!(matches!(err, BaselineError::Io { .. }), "{err}");
    }

    #[test]
    fn load_invalid_toml_is_a_parse_error() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("bad.toml");
        std::fs::write(&path, "not valid [[[ toml").unwrap();

        let err = Baseline::load(&path).unwrap_err();
        assert!(matches!(err, BaselineError::Parse { .. }), "{err}");
    }

    #[test]
    fn load_unknown_top_level_key_is_a_parse_error() {
        // `[[entries]]` (plural) is a typo for `[[entry]]`; without
        // `deny_unknown_fields` this would silently load as zero entries.
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("typo-key.toml");
        std::fs::write(
            &path,
            "[[entries]]\ncode = \"AL001\"\nfile = \"src/a.rs\"\nmessage = \"m\"\ncount = 1\n",
        )
        .unwrap();

        let err = Baseline::load(&path).unwrap_err();
        assert!(matches!(err, BaselineError::Parse { .. }), "{err}");
    }

    #[test]
    fn load_unknown_entry_field_is_a_parse_error() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("typo-field.toml");
        std::fs::write(
            &path,
            "[[entry]]\ncde = \"AL001\"\nfile = \"src/a.rs\"\nmessage = \"m\"\ncount = 1\n",
        )
        .unwrap();

        let err = Baseline::load(&path).unwrap_err();
        assert!(matches!(err, BaselineError::Parse { .. }), "{err}");
    }

    #[test]
    fn load_missing_entry_key_is_an_empty_baseline() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("empty.toml");
        std::fs::write(&path, "# no entries yet\n").unwrap();

        let baseline = Baseline::load(&path).expect("load");
        assert!(baseline.is_empty());
    }

    #[test]
    fn load_folds_duplicate_entries_for_the_same_key() {
        let tmp = TempDir::new().unwrap();
        let path = tmp.path().join("dup.toml");
        std::fs::write(
            &path,
            "[[entry]]\ncode = \"AL001\"\nfile = \"src/a.rs\"\nmessage = \"m\"\ncount = 1\n\n\
             [[entry]]\ncode = \"AL001\"\nfile = \"src/a.rs\"\nmessage = \"m\"\ncount = 2\n",
        )
        .unwrap();

        let baseline = Baseline::load(&path).expect("load");
        assert_eq!(baseline.entries().len(), 1);
        assert_eq!(baseline.entries()[0].count, 3);
    }
}
