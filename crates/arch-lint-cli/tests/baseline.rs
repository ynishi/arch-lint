#[test]
fn json_format_with_baseline_has_only_the_plain_lint_result_keys() {
    let dir = project_with_three_violations();
    let baseline = dir.path().join("b.toml");
    arch_lint(
        dir.path(),
        &[
            "check",
            "--baseline",
            baseline.to_str().unwrap(),
            "--update-baseline",
        ],
    );

    let out = arch_lint(
        dir.path(),
        &[
            "check",
            "--format",
            "json",
            "--baseline",
            baseline.to_str().unwrap(),
        ],
    );
    assert_eq!(code(&out), 0, "stderr: {}", stderr(&out));

    let value: serde_json::Value = serde_json::from_str(&stdout(&out))
        .unwrap_or_else(|e| panic!("not JSON: {e}: {}", stdout(&out)));
    let object = value.as_object().expect("JSON object");
    let mut keys: Vec<&str> = object.keys().map(String::as_str).collect();
    keys.sort_unstable();
    assert_eq!(keys, vec!["files_checked", "violations"], "{value}");
    assert_eq!(object["violations"].as_array().unwrap().len(), 0);
}
