// ── Acceptance 4 ──

#[test]
fn fixing_a_baselined_violation_is_reported_as_stale_then_update_baseline_drops_it() {
    let dir = project_with_three_violations();
    let baseline = dir.path().join("b.toml");
    arch_lint(
        dir.path(),
        &[
            "check",
            "--baseline",
            baseline.to_str().unwrap(),
            "--update-baseline",
        ],
    );

    fs::write(dir.path().join("src/c.rs"), clean_src()).expect("fix src/c.rs");

    let out = arch_lint(
        dir.path(),
        &["check", "--baseline", baseline.to_str().unwrap()],
    );
    assert_eq!(code(&out), 0, "stderr: {}", stderr(&out));
    let err = stderr(&out);
    assert!(err.contains("baseline: 2 suppressed, 1 stale"), "{err}");
    assert!(
        err.contains("baseline: stale entry AL001 src/c.rs"),
        "{err}"
    );
    assert!(err.contains(UNWRAP_MESSAGE), "{err}");

    let out = arch_lint(
        dir.path(),
        &[
            "check",
            "--baseline",
            baseline.to_str().unwrap(),
            "--update-baseline",
        ],
    );
    assert_eq!(code(&out), 0);
    let content = fs::read_to_string(&baseline).expect("rewritten baseline");
    assert_eq!(content.matches("[[entry]]").count(), 2, "{content}");
    assert!(!content.contains("src/c.rs"), "{content}");
}

